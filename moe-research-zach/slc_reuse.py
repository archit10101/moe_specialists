#!/usr/bin/env python
"""semantic-lift-245m-confirm-v1: reuse verification (CPU, read-only). For each of the 16 reused 245M baselines
(TOKEN-4, explicit EDL, Semantic C6, SHUF C6; seeds 0-3) verifies: status COMPLETE, 3,880 steps, 245,032,457 tokens,
plan sha256 (and that the current data code regenerates the same plan), 103,609,728 parameters, model / optimizer /
schedule / batch config == fle_configs.MODEL / TRAIN, budget, seed, the condition block (and table hashes), and the
sha256 of every checkpoint used here (p100; s50 where it exists) recomputed from disk == recorded. Also records code
identity of the reused sll implementation (current sll code-tree hash == the hash logged by the last sll v1 job) and
the hashes of the modules the slc trainer imports. Writes artifacts/semantic-lift-245m-confirm-v1/reuse_manifest.json
(0400, once)."""
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from csr import guard  # noqa: E402


def main():
    guard.check_root()
    from fle_configs import MODEL, TRAIN
    from csr.slc_paths import (ART, N_PARAMS, N_STEPS, PLAN_SHA, REUSED, SHUF_TABLE, SHUF_TABLE_SHA, SLL_ART, TABLE,
                               TABLE_SHA)
    out = ART / "reuse_manifest.json"
    if out.exists():
        print("exists", out)
        return
    res = {"time": guard.now(), "runs": {}, "checks": {}}
    tabs = {TABLE: TABLE_SHA, SHUF_TABLE: SHUF_TABLE_SHA}
    res["tables"] = {t: {"want": s, "got": guard.sha256_file(guard.ROOT / t)} for t, s in tabs.items()}
    tab_ok = all(v["want"] == v["got"] for v in res["tables"].values())
    # plan regenerated by the current data code
    from csr.lfr_lib import main_stream
    _, steps, total = main_stream(245_000_000)
    plan_now = hashlib.sha256(json.dumps(steps).encode()).hexdigest()
    res["plan"] = {"want": PLAN_SHA, "regenerated": plan_now, "n_steps": len(steps), "tokens": int(total),
                   "ok": plan_now == PLAN_SHA and len(steps) == N_STEPS and int(total) == 245_032_457}
    want_cond = {"T4": {}, "EDL": {"edl_beta": 0.005},
                 "C6": {"paper_latent": {"beta": 0.005, "table": TABLE, "table_sha256": TABLE_SHA}},
                 "SHUF": {"paper_latent": {"beta": 0.005, "table": SHUF_TABLE, "table_sha256": SHUF_TABLE_SHA}}}
    all_ok = tab_ok and res["plan"]["ok"]
    for key, rd in REUSED.items():
        c, s = key.split("_s")
        s = int(s)
        st = json.loads((guard.ROOT / rd / "status.json").read_text())
        cfg = json.loads((guard.ROOT / rd / "config.json").read_text())
        chk = {"status": st["status"] == "COMPLETE", "steps": st["steps_done"] == N_STEPS == st["n_steps"],
               "tokens": st["seen"] == 245_032_457 == st["planned_tokens"], "plan": st["plan_sha256"] == PLAN_SHA,
               "params": st["params"]["total_inference"] == N_PARAMS, "model_cfg": cfg["model"] == MODEL,
               "train_cfg": cfg["train"] == TRAIN, "budget": cfg["budget_tokens"] == 245_000_000,
               "seed": cfg["seed"] == s, "cond": cfg["cond"] == want_cond[c],
               "table_sha": (st.get("table_sha256") in (None,) if c in ("T4", "EDL") else
                             st.get("table_sha256") == want_cond[c]["paper_latent"]["table_sha256"])}
        ck = {}
        for tag in ("s50", "p100"):
            e = st["ckpts"].get(tag)
            if not e:
                continue
            meta = json.loads((guard.ROOT / e["path"] / "meta.json").read_text())
            h = guard.sha256_file(guard.ROOT / e["path"] / "state.pt")
            ck[tag] = {"path": e["path"], "step": e["step"], "seen": e["seen"], "sha256_recorded": e["sha256"],
                       "sha256_now": h, "ok": h == e["sha256"] == meta["sha256"] and meta.get("complete") is True}
        chk["ckpts"] = all(v["ok"] for v in ck.values()) and "p100" in ck and ck["p100"]["step"] == N_STEPS
        ok = all(chk.values())
        all_ok = all_ok and ok
        res["runs"][key] = {"run_dir": rd, "experiment": cfg.get("experiment"), "config_sha256":
                            guard.sha256_file(guard.ROOT / rd / "config.json"), "tokens_per_s": st.get("tokens_per_s"),
                            "train_step_seconds": st.get("train_step_seconds"), "checks": chk, "ckpts": ck, "ok": ok}
        print(key, ok, {k: v for k, v in chk.items() if not v}, flush=True)
    # code identity of the reused sll implementation
    import sll_run
    logged = [json.loads(x) for x in (SLL_ART / "RUN_LOG.jsonl").read_text().splitlines()]
    last = logged[-1]["code_tree_sha256"]
    # sll_post_val.py / sll_analyze.py were added after the last logged sll job (post-terminal analysis only); the
    # code tree is recomputed exactly as sll_run.code_hash() but without those two later-added files
    later = {"sll_post_val.py", "sll_analyze.py"}
    h_ = hashlib.sha256()
    fl = sorted([str(p.relative_to(guard.ROOT)) for p in guard.ROOT.glob("sll_*.py")] +
                [str(p.relative_to(guard.ROOT)) for p in (guard.ROOT / "src/csr").glob("sll_*.py")] +
                ["sue_train.py", "scu_evaluate.py", "fle_evaluate.py", "fle_configs.py", "src/csr/lfr_model.py",
                 "src/csr/lfr_eval.py", "src/csr/slk_lib.py", "src/csr/sem_lib.py", "src/csr/gc_lib.py",
                 "src/csr/guard.py"])
    for f in fl:
        if f in later or not (guard.ROOT / f).exists():
            continue
        h_.update(f.encode() + b"\0" + guard.sha256_file(guard.ROOT / f).encode() + b"\n")
    now = h_.hexdigest()
    assert sll_run.code_hash() is not None
    files = ["src/csr/sll_lift.py", "sll_train.py", "src/csr/sll_ckpt.py", "sll_driver.py", "sll_tests.py",
             "sll_tests_train.py", "src/csr/lfr_model.py", "src/csr/lfr_eval.py", "src/csr/lfr_lib.py",
             "src/csr/slk_lib.py", "src/csr/gc_lib.py", "src/csr/fsp_lib.py", "fle_configs.py", "fle_evaluate.py",
             "slc_train.py", "src/csr/slc_ckpt.py", "slc_driver.py"]
    res["code"] = {"sll_code_tree_sha256_last_sll_job": last, "sll_code_tree_sha256_now": now,
                   "sll_code_unchanged_since_last_sll_job": last == now,
                   "files": {f: guard.sha256_file(guard.ROOT / f) for f in files},
                   "generation": json.loads((guard.ROOT / ".tmp/semantic-lift-245m-confirm-v1/gen_slc_code.json").read_text())}
    for v in res["code"]["generation"].values():
        v.pop("diff", None)
    res["checks"]["code_unchanged"] = last == now
    res["lineage_note"] = ("E/F trainer slc_train.py = path-only copy of sll_train.py; sll_train = sue_train (utility "
                           "refused) + cond['lift']; sue_train = slk_train + cond['utility'] branch only; slk_train = "
                           "path-only copy of sem_train, which trained P1_C6/P1_SHUF/P1_T4_s3/P1_EDL_s2-3. fle T4/EDL "
                           "finals: slk_gpu_checks T-EQ (step-0 identity of slk_train TOKEN-4 vs fle final_T4_s0).")
    slk_g = guard.ROOT / "artifacts/semantic-edl-long-k/gpu_checks.json"
    res["slk_gpu_checks_sha256"] = guard.sha256_file(slk_g) if slk_g.exists() else None
    res["all_ok"] = bool(all_ok and res["checks"]["code_unchanged"])
    guard.atomic_write_json(out, res, mode=0o400)
    print(json.dumps({"all_ok": res["all_ok"], "plan": res["plan"], "tables_ok": tab_ok,
                      "code_unchanged": res["checks"]["code_unchanged"]}))
    sys.exit(0 if res["all_ok"] else 1)


if __name__ == "__main__":
    main()
